/**
 * Central catalogue of external services (spec §37). The UI renders the
 * provider settings / diagnostics screens from this list; adapters read
 * their endpoints from here. No secrets live in this file – keys are entered
 * by the user (stored in SecureStore) or configured on the TrailPack API server.
 */

export type ProviderKind = 'map_tiles' | 'routing' | 'geocoding' | 'poi' | 'weather' | 'elevation' | 'ai' | 'sync' | 'radar' | 'transit';

export interface ProviderInfo {
  id: string;
  name: string;
  kinds: ProviderKind[];
  /** Works without any key. */
  free: boolean;
  requiresKey: boolean;
  /** Where the key lives: on device (user entered) or only on the TrailPack API server. */
  keyLocation?: 'device' | 'server' | 'device_or_server';
  keyDescription?: string;
  docsUrl: string;
  signupUrl?: string;
  features: string[];
  limits: string;
  cost: string;
  attribution?: string;
  license?: string;
  enabledByDefault: boolean;
}

